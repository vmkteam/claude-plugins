package rpc

import (
	"context"
	"net/http"

	"projsrv/pkg/db"

	"github.com/vmkteam/zenrpc/v2"
)

var (
	ErrNotFound      = zenrpc.NewStringError(http.StatusNotFound, "not found")
	ErrInvalidStatus = zenrpc.NewStringError(http.StatusBadRequest, "invalid status")
)

func newInternalError(err error) *zenrpc.Error {
	return zenrpc.NewError(http.StatusInternalServerError, err)
}

type ProjectService struct {
	zenrpc.Service
	repo db.ProjectRepo
}

func NewProjectService(dbo db.DB) *ProjectService {
	return &ProjectService{repo: db.NewProjectRepo(dbo)}
}

// Archive archives an active project of the current user.
//
//zenrpc:projectId project id
//zenrpc:return bool
//zenrpc:400 Invalid status
//zenrpc:404 Not Found
func (s ProjectService) Archive(ctx context.Context, projectId int) (bool, error) {
	p, err := s.repo.ProjectByID(ctx, projectId)
	if err != nil {
		return false, newInternalError(err)
	} else if p == nil || p.UserID != UserFromContext(ctx).ID {
		return false, ErrNotFound
	} else if p.StatusID != db.StatusActive {
		return false, ErrInvalidStatus
	}
	p.StatusID = db.StatusArchived
	ok, err := s.repo.UpdateProject(ctx, p)
	if err != nil {
		return false, newInternalError(err)
	}
	return ok, nil
}
EOF

