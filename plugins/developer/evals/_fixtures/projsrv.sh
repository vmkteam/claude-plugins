// withUser puts an authenticated user into ctx, as auth middleware does.
func withUser(ctx context.Context, userID int) context.Context {
	return context.WithValue(ctx, userKey, User{ID: userID})
}

func TestDBProjectService_Get(t *testing.T) {
	ctx := t.Context()
	repo := db.NewProjectRepo(testDB)

	t.Run("project is readable by id", func(t *testing.T) {
		p, clean := test.Project(t, testDB, &db.Project{UserID: 10, StatusID: db.StatusActive})
